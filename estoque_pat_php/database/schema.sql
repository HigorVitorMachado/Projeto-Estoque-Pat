-- Banco de dados Gestão de Estoque - MySQL 8+ / MariaDB (XAMPP)
-- Crie o banco 'estoque' no phpMyAdmin antes de importar este arquivo.

CREATE TABLE IF NOT EXISTS setor (
    ID_SETOR INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    NOME_SETOR VARCHAR(100) NOT NULL,
    RESPONSAVEL VARCHAR(100) NULL,
    MODULOS VARCHAR(255) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS fornecedor (
    ID_FORNECEDOR INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    RAZAO_SOCIAL VARCHAR(150) NOT NULL,
    CNPJ VARCHAR(20) NOT NULL UNIQUE,
    CONTATO VARCHAR(100) NULL,
    ENDERECO VARCHAR(255) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS usuario (
    ID_USUARIO INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    LOGIN VARCHAR(50) NOT NULL UNIQUE,
    SENHA VARCHAR(255) NOT NULL,
    STATUS VARCHAR(20) NULL,
    ID_SETOR INT NULL,
    PERFIL VARCHAR(20) NOT NULL DEFAULT 'comum',
    MODULOS VARCHAR(255) NULL,
    CONSTRAINT fk_usuario_setor FOREIGN KEY (ID_SETOR) REFERENCES setor(ID_SETOR)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS produto (
    ID_PRODUTO INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    NOME_PRODUTO VARCHAR(100) NOT NULL UNIQUE,
    QTD_MINIMA INT NULL,
    ESTOQUE INT NOT NULL DEFAULT 0,
    PRECO DECIMAL(10,2) NULL,
    CLASSIFICACAO VARCHAR(50) NULL,
    ID_FORNECEDOR INT NULL,
    CODIGO VARCHAR(30) NULL UNIQUE,
    DESCRICAO VARCHAR(255) NULL,
    UNIDADE_MEDIDA VARCHAR(20) NULL,
    CONSTRAINT fk_produto_fornecedor FOREIGN KEY (ID_FORNECEDOR) REFERENCES fornecedor(ID_FORNECEDOR)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS pedido_compra (
    ID_PEDIDO INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    QUANTIDADE INT NULL,
    STATUS VARCHAR(50) NULL,
    DATA DATE NULL,
    ID_USUARIO INT NULL,
    ID_PRODUTO INT NULL,
    NOME_PRODUTO VARCHAR(100) NULL,
    CONSTRAINT fk_pedido_usuario FOREIGN KEY (ID_USUARIO) REFERENCES usuario(ID_USUARIO),
    CONSTRAINT fk_pedido_produto FOREIGN KEY (ID_PRODUTO) REFERENCES produto(ID_PRODUTO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS entrada (
    ID_ORDEM_ENTRADA INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    QUANTIDADE INT NULL,
    DATA DATE NULL,
    ID_PEDIDO INT NULL,
    ID_PRODUTO INT NULL,
    CONSTRAINT fk_entrada_pedido FOREIGN KEY (ID_PEDIDO) REFERENCES pedido_compra(ID_PEDIDO),
    CONSTRAINT fk_entrada_produto FOREIGN KEY (ID_PRODUTO) REFERENCES produto(ID_PRODUTO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS saida (
    ID_ORDEM_SAIDA INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    QUANTIDADE INT NULL,
    DATA DATE NULL,
    ID_USUARIO INT NULL,
    ID_PRODUTO INT NULL,
    CONSTRAINT fk_saida_usuario FOREIGN KEY (ID_USUARIO) REFERENCES usuario(ID_USUARIO),
    CONSTRAINT fk_saida_produto FOREIGN KEY (ID_PRODUTO) REFERENCES produto(ID_PRODUTO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS movimentacao (
    ID_MOVIMENTACAO INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    QUANTIDADE INT NULL,
    DATA DATE NULL,
    OBSERVACAO VARCHAR(255) NULL,
    ID_ENTRADA INT NULL,
    ID_SAIDA INT NULL,
    CONSTRAINT fk_movimentacao_entrada FOREIGN KEY (ID_ENTRADA) REFERENCES entrada(ID_ORDEM_ENTRADA),
    CONSTRAINT fk_movimentacao_saida FOREIGN KEY (ID_SAIDA) REFERENCES saida(ID_ORDEM_SAIDA)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

